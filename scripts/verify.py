#!/usr/bin/env python3
"""Verify the ltslab patch set.

  scripts/verify.py                   check that manifest.yaml, cves/, and patches/ agree
  scripts/verify.py index             write CVES.md, the CVE list, from cves/*.yaml
  scripts/verify.py apply [PROJECT]   apply each series to its pinned commit in work/
  scripts/verify.py cve [CVE]         prove Red and Green for each CVE with verify.tests

Without PROJECT or CVE, apply and cve run for all of them. Requires PyYAML, git, Maven 3.9+, and the JDKs
that scripts/release.py needs.
"""

import functools
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET
import zipfile
from concurrent.futures import ThreadPoolExecutor
from datetime import date
from pathlib import Path

import toolchain
import yaml
from toolchain import MANIFEST, ROOT, WORK

GIT = ["git", "-c", "user.name=ltslab", "-c", "user.email=ltslab@invalid",
       "-c", "advice.detachedHead=false"]
STATUSES = {"no-patch", "patched", "verified", "released"}

PROJECTS = MANIFEST["projects"]
CVES = {p.stem: yaml.safe_load(p.read_text()) for p in sorted((ROOT / "cves").glob("*.yaml"))}


def patch_dir(project):
    return ROOT / "patches" / project / str(PROJECTS[project]["tag"]).removeprefix("v")


def series(project):
    path = patch_dir(project) / "series"
    return path.read_text().split() if path.is_file() else []


def patched(project):
    """Artifact ID -> {path under src/main/: module directory} for the main sources that the project's patches
    change. A test-only module (*-tests/) is not published, so it does not count."""
    prefix, out = PROJECTS[project].get("publish", {}).get("prefix", ""), {}
    for n in series(project):
        for path in re.findall(r"^diff --git a/(\S+)", (patch_dir(project) / n).read_text(errors="replace"), re.M):
            if "/src/main/" in path and not re.search(r"-tests/", path):
                directory, rest = path.split("/src/main/", 1)
                out.setdefault(prefix + directory.split("/")[-1], {})[rest] = directory
    return out


INDEX = ROOT / "CVES.md"
DEPENDENCIES = ROOT / "cves" / "dependencies.json"
MEANING = {"verified": "patched, and a test proves it (Red before the fix, Green after)",
           "patched": "patched, without a test that proves it", "no-patch": "not patched yet",
           "released": "verified and in a published release"}


def status(cve):
    """A third-party CVE's state: released, fixed in the next release, or not fixed and why."""
    if cve.get("released"):
        return f"fixed in {cve['released']}"
    return "fixed in the next release" if cve["fixed"] else f"not fixed: {cve['note']}"


def index():
    """The CVE list, generated from cves/*.yaml so that it cannot drift."""
    rows = [f"| [{i}](cves/{i}.yaml) | {c['project']} | {c['severity']} | {c['status']} | "
            f"{'yes' if PROJECTS[c['project']]['scope'] == 'v1' else 'no'} | "
            f"[{c['title'].replace('|', '/')}]({c['advisory']}) |" for i, c in CVES.items()]
    deps = json.loads(DEPENDENCIES.read_text()) if DEPENDENCIES.is_file() else {"boot": "?", "cves": []}
    third = [f"| [{c['id']}]({c['advisory']}) | `{c['artifact']}` | {c['severity'].lower() or '-'} | {c['boot']} | "
             f"{c['ltslab']} | {status(c)} |"
             for c in sorted(deps["cves"], key=lambda c: (c["fixed"], c["artifact"], c["id"]))]
    return "\n".join(["# CVEs", "", "Generated by `scripts/verify.py index` from [`cves/`](cves/); do not edit.", "",
                      "## Spring and Reactor", "",
                      "LTS for Spring patches these projects; each CVE has its own file.", "",
                      *[f"- **{k}:** {v}" for k, v in MEANING.items()],
                      "- **Built:** whether the project is in the release (`scope: v1` in `manifest.yaml`)", "",
                      "| CVE | Project | Severity | Status | Built | Advisory |", "|---|---|---|---|---|---|",
                      *rows, "",
                      "## Third-party libraries", "",
                      f"Known CVEs (from OSV) in the libraries that Spring Boot {deps['boot']}'s BOM manages, "
                      "and whether "
                      "the LTS for Spring BOM's version fixes them, and in which release. "
                      "`scripts/dependencies.py` writes the data to "
                      "[`cves/dependencies.json`](cves/dependencies.json).", "",
                      "| CVE | Library | Severity | Spring Boot | LTS for Spring | Status |",
                      "|---|---|---|---|---|---|",
                      *third, ""])


def check():
    """Check that manifest.yaml, the patch series, cves/*.yaml, and CVES.md agree, and that no tracked file has a
    local path or a personal mail address; print each error."""
    errors = []
    for project in PROJECTS:
        listed, on_disk = set(series(project)), {f.name for f in patch_dir(project).glob("*.patch")}
        if not listed or listed != on_disk:
            errors.append(f"{project}: series and patch files differ: {sorted(listed ^ on_disk)}")
        publish = PROJECTS[project].get("publish")
        if (PROJECTS[project]["scope"] == "v1") != bool(publish):
            errors.append(f"{project}: manifest.yaml needs publish exactly when scope is v1")
        elif publish:  # republish exactly the modules whose main code the patches change
            changed = set(patched(project))
            if changed != set(publish["modules"]):
                errors.append(f"{project}: publish.modules must be the modules the patches change: {sorted(changed)}")
    dirs = {d.relative_to(ROOT / "patches").as_posix() for d in (ROOT / "patches").glob("*/*")}
    expected = {patch_dir(p).relative_to(ROOT / "patches").as_posix() for p in PROJECTS}
    if dirs != expected:
        errors.append(f"patch directories differ from manifest.yaml: {sorted(dirs ^ expected)}")

    claimed = set()
    for cve_id, c in CVES.items():
        where, patches = f"cves/{cve_id}.yaml", c.get("patches") or []
        if c.get("id") != cve_id or c.get("project") not in PROJECTS or c.get("status") not in STATUSES:
            errors.append(f"{where}: id, project, or status is invalid")
            continue
        if (c["status"] == "no-patch") != (not patches):
            errors.append(f"{where}: status is no-patch exactly when there are no patches")
        if c["status"] in {"verified", "released"} and not all(
                (c.get("verify") or {}).get(k) for k in ("tests", "red", "green")):
            errors.append(f"{where}: {c['status']} needs verify.tests, red, and green")
        names = series(c["project"])
        if patches and (patches[0] not in names or
                        names[names.index(patches[0]):names.index(patches[0]) + len(patches)] != patches):
            errors.append(f"{where}: patches must be a consecutive run of the series, in order")
        claimed |= {(c["project"], p) for p in patches}
    for project in PROJECTS:
        errors += [f"{project}: {n} is not listed by any CVE" for n in series(project)
                   if (project, n) not in claimed]

    # Personal data: no local paths anywhere, and no personal mail addresses outside patches/, whose headers
    # keep the upstream authors.
    for name in subprocess.run(["git", "ls-files", "-z"], cwd=ROOT, capture_output=True, text=True).stdout.split("\0"):
        text = (ROOT / name).read_text(errors="replace") if name and (ROOT / name).is_file() else ""
        if re.search(r"/home/\w|/Users/\w|\w:\\Users\\", text) or (not name.startswith("patches/") and re.search(
                r"@(gmail|googlemail|outlook|hotmail|live|yahoo|icloud|me)\.com\b", text)):
            errors.append(f"{name}: contains a local path or a personal mail address")
    deps = json.loads(DEPENDENCIES.read_text()) if DEPENDENCIES.is_file() else {}
    if deps.get("boot") != MANIFEST["boot"] or set(MANIFEST["bom"].get("lines", {})) - set(deps.get("properties", {})):
        errors.append("cves/dependencies.json does not match manifest.yaml; run scripts/dependencies.py update")
    if not INDEX.is_file() or INDEX.read_text() != index():
        errors.append("CVES.md is out of date; run scripts/verify.py index")
    for e in errors:
        print(f"error: {e}", file=sys.stderr)
    print(f"{len(PROJECTS)} projects, {sum(len(series(p)) for p in PROJECTS)} patches, "
          f"{len(CVES)} CVEs: {'ok' if not errors else f'{len(errors)} errors'}")
    return not errors


def checkout(project):
    """Return work/<project> reset to the pinned commit."""
    p, d = PROJECTS[project], WORK / project
    if not (d / ".git").is_dir():
        cloned = subprocess.run([*GIT, "clone", "-q", "--depth", "1", "--branch", str(p["tag"]),
                                 p["upstream"], str(d)], capture_output=True, text=True)
        if cloned.returncode != 0:
            raise SystemExit(f"error: {project}: git clone failed\n{cloned.stderr}")
    tagged = subprocess.run(["git", "rev-parse", f"{p['tag']}^{{commit}}"], cwd=d,
                            capture_output=True, text=True).stdout.strip()
    if tagged != p["commit"]:
        raise SystemExit(f"error: {project}: tag {p['tag']} is {tagged}, not {p['commit']}")
    subprocess.run([*GIT, "am", "--abort"], cwd=d, capture_output=True)
    subprocess.run([*GIT, "checkout", "-q", "-f", "-B", "ltslab", p["commit"]], cwd=d, check=True)
    subprocess.run(["git", "clean", "-q", "-fd"], cwd=d, check=True)
    return d


def am(d, project, names):
    for n in names:
        subprocess.run([*GIT, "am", "-q", str(patch_dir(project) / n)], cwd=d, check=True)


def apply(project):
    am(checkout(project), project, series(project))
    print(f"{project}: {len(series(project))} patches apply to {PROJECTS[project]['commit'][:12]}")
    return True


@functools.cache
def tracked(project, commit):
    """The paths of the files in the project's commit."""
    return subprocess.run(["git", "ls-tree", "-r", "--name-only", commit], cwd=WORK / project,
                          capture_output=True, text=True, check=True).stdout.splitlines()


def module_directory(project, commit, module):
    """The module's directory in the commit; a sample or docs folder of the same name is deeper."""
    prefix = PROJECTS[project]["publish"].get("prefix", "")
    found = {Path(n.split("/src/")[0]) for n in tracked(project, commit) if "/src/" in n}
    return min((d for d in found if prefix + d.name == module), key=lambda d: (len(d.parts), d))


def test_paths(project, commit, directories):
    """The paths of the commit that the tests of modules in the directories need: those directories, the test
    fixtures, and the POMs, Maven settings, and Maven wrapper that a Maven project's module builds with."""
    names = tracked(project, commit)
    fixtures = {n.split("/src/testFixtures/")[0] + "/src/testFixtures" for n in names if "/src/testFixtures/" in n}
    poms = {n for n in names if n.split("/")[-1] == "pom.xml"}
    return sorted({*(d.as_posix() for d in directories), *fixtures, *poms,
                   *(".mvn" for n in names if n.startswith(".mvn/")), *(n for n in names if n == "mvnw")})


def test_sources(tree, directory, classes, extra):
    """(sources, sourcepath, resource folders) to compile and run the module's test classes. javac takes the test
    helpers and fixtures that the sources use from the sourcepath; extra adds what only run time needs."""
    sets = sorted((tree / directory / "src").glob("*test*/java"))  # src/test/java, src/integration-test/java
    sourcepath = [*sets, *sorted(tree.glob("*/src/testFixtures/java")), *sorted(tree.glob("*/*/src/testFixtures/java"))]
    sources = [s / f"{n.replace('.', '/')}.java" for n in classes for s in sets
               if (s / f"{n.replace('.', '/')}.java").is_file()]
    resources = [r.parent / "resources" for r in sourcepath if (r.parent / "resources").is_dir()]
    # A class that only a service file names, such as a JUnit launcher listener, is not referenced by the tests.
    providers = {line.split("#")[0].strip() for r in resources if (r / "META-INF/services").is_dir()
                 for f in (r / "META-INF/services").iterdir() for line in f.read_text().splitlines()} - {""}
    sources += [f for n in sorted(providers) for s in sourcepath
                for f in [s / f"{n.replace('.', '/')}.java"] if f.is_file()]
    sources += [tree / f for f in extra if f.startswith(f"{directory}/") and f.endswith(".java")]
    # Some builds keep test resources next to the sources.
    return sources, sourcepath, resources + sets


def coordinates(project, module, version):
    """The tests' dependencies: the module at version, the test libraries, and the compile dependencies. The test
    libraries come first, because the order of the classpath picks service providers; a library listed twice, such
    as the module under test, is declared once, and the project's own modules are at version."""
    p = PROJECTS[project]
    g, up = p["publish"]["group"], str(p["tag"]).removeprefix("v")
    found = {}
    for dg, da, dv in (x.split(":") for x in [f"{g}:{module}:{version}", *p.get("test", []), *p.get("compile", [])]):
        found.setdefault((dg, da), version if dg == g and dv == up else dv)
    return [f"{dg}:{da}:{dv}" for (dg, da), dv in found.items()]


def test_runs(ids, train):
    """One test run per CVE, phase, and module, each with its sources unpacked in work/cve/<CVE>/<phase>/. Red runs
    the tests after the test patch on the upstream release; Green runs them after the CVE's patches on this run's
    train, (version, repository URL) per project."""
    def unpack(job):
        cve_id, phase = job
        c = CVES[cve_id]
        project, p = c["project"], PROJECTS[c["project"]]
        names, patches = series(project), c["patches"]
        up = str(p["tag"]).removeprefix("v")
        commits = subprocess.run(["git", "rev-list", "--reverse", f"{p['commit']}..ltslab"], cwd=WORK / project,
                                 capture_output=True, text=True, check=True).stdout.split()
        at = names.index(patches[0]) + (0 if phase == "red" else len(patches) - 1)
        version = up if phase == "red" else train[project][0]
        out = WORK / "cve" / cve_id / phase
        shutil.rmtree(out, ignore_errors=True)
        tree = out / "tree"
        tree.mkdir(parents=True)
        extra, runs = c["verify"].get("sources", []), []
        modules = sorted({t.split(":")[0] for t in c["verify"]["tests"]})
        directories = {m: module_directory(project, commits[at], m) for m in modules}
        wanted = test_paths(project, commits[at], directories.values()) + extra
        subprocess.run(f"git archive {commits[at]} {' '.join(map(shlex.quote, wanted))} | tar -x -C {tree}",
                       shell=True, cwd=WORK / project, check=True)
        for module in modules:
            directory = directories[module]
            tests = [t.split(":", 1)[1] for t in c["verify"]["tests"] if t.startswith(f"{module}:")]
            sources, sourcepath, resources = test_sources(tree, directory, sorted(
                {re.sub(r"\.[a-z]\w*$", "", n) for n in tests}), extra)  # a filter may end in a method name
            # As with Gradle's --tests, a class that a later patch adds is left out, but one must exist.
            present = {s.relative_to(sp).as_posix().removesuffix(".java").replace("/", ".")
                       for s in sources for sp in sourcepath if s.is_relative_to(sp)}
            tests = [n for n in tests if re.sub(r"\.[a-z]\w*$", "", n) in present]
            if not tests:
                raise SystemExit(f"error: {cve_id} {phase}: {module} has none of the test classes")
            # A Maven project's module runs its tests with its own POM, which prepares them as upstream's build does.
            own = (tree / directory / "pom.xml").is_file()
            runs.append({"cve": cve_id, "phase": phase, "project": project, "module": module, "version": version,
                         "dir": out / module, "tests": tests, "sources": sources, "sourcepath": sourcepath,
                         "resources": resources, "repository": train[project][1],
                         "own": tree / directory if own else None, "tree": tree,
                         "reports": (tree / directory if own else out / module) / "target" / "surefire-reports",
                         "kotlin": [tree / f for f in extra if f.startswith(f"{directory}/") and f.endswith(".kt")]})
        return runs

    with ThreadPoolExecutor(os.cpu_count() or 2) as pool:
        return [r for runs in pool.map(unpack, [(i, phase) for i in ids for phase in ("red", "green")]) for r in runs]


def surefire_filter(tests):
    """Surefire's filter, Class#method, for Gradle's package.Class.method."""
    return ",".join(re.sub(r"^(?:[a-z]\w*\.)*([A-Z]\w*)(?:\.(\w+))?$",
                           lambda m: m[1] + (f"#{m[2]}" if m[2] else ""), n) for n in tests)


def artifact(run):
    return f"{run['cve']}-{run['phase']}-{run['module']}"


def test_pom(run, after=None):
    """The POM of one test run: Surefire runs its tests, on the JDK, environment, and JVM arguments that the upstream
    build gives them, and kotlin-maven-plugin compiles its Kotlin, if any. A run after another depends on that run's
    POM alone, so that Maven runs it later."""
    p = PROJECTS[run["project"]]
    kotlin = run["kotlin"] and next(x.split(":")[2] for x in p["test"] if x.startswith("org.jetbrains.kotlin:"))
    environment = "".join(f"<{k}>{v}</{k}>" for k, v in p.get("test-env", {}).items())
    args = " ".join(p.get("test-args", {}).get("all", []) + p.get("test-args", {}).get(run["module"], []))
    build = (f"<testOutputDirectory>{run['dir'] / 'classes'}</testOutputDirectory><plugins><plugin>"
             "<groupId>org.apache.maven.plugins</groupId><artifactId>maven-surefire-plugin</artifactId>"
             f"<version>3.5.4</version><configuration><jvm>{toolchain.jdks()[p['test-jdk']] / 'bin' / 'java'}</jvm>"
             f"<test>{surefire_filter(run['tests'])}</test><testFailureIgnore>true</testFailureIgnore>"
             f"<environmentVariables>{environment}</environmentVariables><argLine>{args}</argLine></configuration>"
             "</plugin>")
    if kotlin:
        build += ("<plugin><groupId>org.jetbrains.kotlin</groupId><artifactId>kotlin-maven-plugin</artifactId>"
                  f"<version>{kotlin}</version><configuration><sourceDirs><sourceDir>{run['dir'] / 'kotlin'}"
                  "</sourceDir></sourceDirs></configuration></plugin>")
    pom = toolchain.pom(coordinates(run["project"], run["module"], run["version"]), [run["repository"]],
                        build + "</plugins>", artifact(run))
    if after:
        pom = pom.replace("</dependencies>", f"<dependency><groupId>ltslab</groupId><artifactId>{after}</artifactId>"
                          "<version>1</version><type>pom</type><exclusions><exclusion><groupId>*</groupId>"
                          "<artifactId>*</artifactId></exclusion></exclusions></dependency></dependencies>", 1)
    return pom


def compile_tests(run, classpath):
    """Compile the run's tests and copy their resources into its classes; whether they compile. Kotlin that only
    run time needs compiles with kotlin-maven-plugin."""
    p, d = PROJECTS[run["project"]], run["dir"]
    with open(d / "verify.log", "a") as output:
        error = toolchain.javac(toolchain.jdks()[max(toolchain.jdks())], p["test-jdk"], ["-parameters", "-g"],
                                classpath, run["sources"], d / "classes", run["sourcepath"])
        if error:
            output.write(error)
            return False
        if run["kotlin"]:
            kotlin = next(x.split(":")[2] for x in p["test"] if x.startswith("org.jetbrains.kotlin:"))
            if subprocess.run(["mvn", "-q", "-B", "-f", str(d / "pom.xml"),
                               f"org.jetbrains.kotlin:kotlin-maven-plugin:{kotlin}:compile"],
                              stdout=output, stderr=subprocess.STDOUT).returncode:
                return False
            shutil.copytree(d / "target" / "classes", d / "classes", dirs_exist_ok=True)
    for r in run["resources"]:  # some builds keep test resources next to the sources
        shutil.copytree(r, d / "classes", dirs_exist_ok=True,
                        ignore=lambda _, files: [f for f in files if f.endswith(".java")])
    return True


def own_pom(run):
    """The Maven command that runs the tests of a Maven project's module with its own POM, in the unpacked sources.
    The POM gets the project's other patched modules as direct dependencies at the run's version, the train's for
    Green, and javac compiles only the run's tests and what they use. A module on Maven Central is not compiled: its
    jar at that version is unpacked as its classes."""
    import release  # which also registers the POM namespace for writing
    p, d = PROJECTS[run["project"]], run["own"]
    g, up = p["publish"]["group"], str(p["tag"]).removeprefix("v")
    tree = ET.parse(d / "pom.xml")
    root = tree.getroot()

    def child(parent, tag):
        found = parent.find(release.q(tag))
        return found if found is not None else ET.SubElement(parent, release.q(tag))

    def element(tag, **children):
        e = ET.Element(release.q(tag))
        for k, v in children.items():
            ET.SubElement(e, release.q(k)).text = v
        return e

    for m in p["publish"]["modules"]:
        if m != run["module"]:
            child(root, "dependencies").insert(0, element("dependency", groupId=g, artifactId=m,
                                                           version=run["version"]))
    child(root, "repositories").insert(0, element("repository", id="train", url=run["repository"]))
    compiler = element("plugin", groupId="org.apache.maven.plugins", artifactId="maven-compiler-plugin")
    includes = child(child(compiler, "configuration"), "testIncludes")
    for source in run["sources"]:
        found = next(s for s in run["sourcepath"] if source.is_relative_to(s))
        ET.SubElement(includes, release.q("testInclude")).text = source.relative_to(found).as_posix()
    child(child(root, "build"), "plugins").append(compiler)
    tree.write(d / "pom.xml", xml_declaration=True, encoding="UTF-8")
    # Only the files that the tests need are unpacked, so the checks of the build, such as Checkstyle, are skipped;
    # Spring Cloud's build skips them with disable.checks. Surefire runs once, not in each execution of the POM.
    command = [*toolchain.maven(run["tree"]), "-q", "-B", "-f", str(d / "pom.xml"), "test-compile", "surefire:test",
               f"-Dtest={surefire_filter(run['tests'])}", "-Dsurefire.failIfNoSpecifiedTests=false",
               "-Dmaven.test.failure.ignore=true", "-Dcheckstyle.skip=true", "-Ddisable.checks=true"]
    if not toolchain.exists(g, run["module"], up):  # such as a module of integration tests
        return command
    name = f"{run['module']}-{run['version']}.jar"
    if run["phase"] == "red":
        jar = toolchain.CACHE / "jars" / name
        if not jar.is_file():
            jar.parent.mkdir(parents=True, exist_ok=True)
            jar.write_bytes(toolchain.fetch(toolchain.url(g, run["module"], up, "jar"))[1])
    else:
        jar = release.UPSTREAM / g.replace(".", "/") / run["module"] / run["version"] / name
    with zipfile.ZipFile(jar) as z:
        z.extractall(d / "target" / "classes")
    return [*command, "-Dmaven.main.skip=true", "-Daspectj.skip=true"]


def prove(ids):
    """Prove the CVEs with a few Maven runs. A Gradle project's runs share them: one resolves every test classpath,
    javac compiles the tests, and one per project runs them with Surefire. A Maven project's module runs with its own
    POM. Each project's train is built first."""
    import release  # scripts/release.py imports this module, so it is imported only here, to build the trains
    projects = sorted({CVES[i]["project"] for i in ids})
    with ThreadPoolExecutor(max(1, (os.cpu_count() or 2) // 2)) as pool:
        list(pool.map(release.build, projects))
    # Maven would use an -ltslab module that an earlier run left in ~/.m2 instead of this run's.
    for project in projects:
        p = PROJECTS[project]
        for stale in (toolchain.LOCAL / p["publish"]["group"].replace(".", "/")).glob(
                f"*/{str(p['tag']).removeprefix('v')}-ltslab.*"):
            shutil.rmtree(stale, ignore_errors=True)
    runs = test_runs(ids, {p: (release.version(p), release.UPSTREAM.as_uri()) for p in projects})
    print(f"{len(ids)} CVEs: {len(runs)} test runs", flush=True)
    top = WORK / "cve"

    # The classpath is the same for every run of a project's module at one version, so it resolves once.
    keys = sorted({(r["project"], r["module"], r["version"]) for r in runs if not r["own"]})
    for project, module, version in keys:
        d = top / "classpath" / f"{module}-{version}"
        d.mkdir(parents=True, exist_ok=True)
        repository = next(r["repository"] for r in runs if r["project"] == project)
        (d / "pom.xml").write_text(toolchain.pom(coordinates(project, module, version), [repository],
                                                 artifact=f"{module}-{version}"))
    if keys:
        with open(top / "classpath.log", "w") as output:
            subprocess.run([*toolchain.reactor(top / "classpath", [f"{m}-{v}" for _, m, v in keys]),
                            "dependency:build-classpath", "-Dmdep.outputFile=classpath.txt"],
                           stdout=output, stderr=subprocess.STDOUT)
    classpaths = {(p, m, v): (top / "classpath" / f"{m}-{v}" / "classpath.txt") for p, m, v in keys}

    def prepare(run):
        run["dir"].mkdir(parents=True)
        if run["own"]:
            return True
        (run["dir"] / "kotlin").mkdir()
        for f in run["kotlin"]:
            shutil.copy(f, run["dir"] / "kotlin" / f.name)
        (run["dir"] / "pom.xml").write_text(test_pom(run))
        classpath = classpaths[(run["project"], run["module"], run["version"])]
        if not classpath.is_file():
            (run["dir"] / "verify.log").write_text(f"Maven cannot resolve the classpath; see {top / 'classpath.log'}\n")
            return False
        return compile_tests(run, classpath.read_text().strip())

    with ThreadPoolExecutor(os.cpu_count() or 2) as pool:
        compiled = list(pool.map(prepare, runs))
    ready = [r for r, ok in zip(runs, compiled, strict=True) if ok]
    # Upstream tests may listen on fixed ports, so tests run in parallel only where Gradle runs them so: a module's
    # runs take turns, and so do all of a project's if its build does not set org.gradle.parallel. One Maven run on
    # every CPU runs them all, each run after the one before it in turn, which it depends on.
    gradle = [r for r in ready if not r["own"]]
    turns = {}
    for r in gradle:
        parallel = "org.gradle.parallel=true" in ((WORK / r["project"] / "gradle.properties").read_text()
                                                 if (WORK / r["project"] / "gradle.properties").is_file() else "")
        turn = turns.setdefault((r["project"], r["module"] if parallel else None), [])
        (r["dir"] / "pom.xml").write_text(test_pom(r, artifact(turn[-1]) if turn else None))
        turn.append(r)

    def surefire():
        with open(top / "surefire.log", "w") as output:
            subprocess.run([*toolchain.reactor(top, [os.path.relpath(r["dir"], top) for r in gradle]),
                            "surefire:test"], stdout=output, stderr=subprocess.STDOUT)

    def own(project):  # a Maven project's runs take turns
        with open(top / f"surefire-{project}.log", "w") as output:
            for r in ready:
                if r["project"] == project and r["own"]:
                    subprocess.run(own_pom(r), cwd=r["tree"], stdout=output, stderr=subprocess.STDOUT)

    with ThreadPoolExecutor(len(projects) + 1) as pool:
        jobs = [pool.submit(surefire)] if gradle else []
        jobs += [pool.submit(own, p) for p in sorted({r["project"] for r in ready if r["own"]})]
        [job.result() for job in jobs]

    ok = True
    for cve_id in ids:
        results = {}
        for phase in ("red", "green"):
            mine = [r for r in runs if r["cve"] == cve_id and r["phase"] == phase]
            reports = sorted(f for r in mine for f in r["reports"].glob("TEST-*.xml"))  # in a fixed order
            cases = [c for f in reports for c in ET.parse(f).getroot().iter("testcase")]
            failed = [c for c in cases if c.find("failure") is not None or c.find("error") is not None]
            # A run that did not compile, or whose test JVM did not report, fails.
            code = int(bool(failed) or any(not r["reports"].is_dir() for r in mine))
            log = "".join((r["dir"] / "verify.log").read_text() for r in mine if (r["dir"] / "verify.log").is_file())
            surefire_log = top / (f"surefire-{CVES[cve_id]['project']}.log" if any(r["own"] for r in mine)
                                  else "surefire.log")
            results[phase] = code, cases, failed, log or f"see {surefire_log}"
        ok &= judge(cve_id, results["red"], results["green"])
    return ok


def judge(cve_id, red, green):
    """Print the CVE's Red and Green results, each (exit code, test cases, failed cases, log), as cves/*.yaml records
    them; whether the new test fails an assertion before the fix and the same tests pass after it."""
    code, cases, failed, log = red
    asserted = [f for f in failed if f.find("failure") is not None]
    red_ok = code != 0 and bool(asserted)
    red_ok or print(*log.splitlines()[-40:], sep="\n")
    red = (f"{len(asserted)} of {len(cases)} failed ({asserted[0].find('failure').get('type', '').split('.')[-1]}"
           f" in {asserted[0].get('name').replace(chr(34), chr(39))})" if red_ok else
           f"not Red: exit {code}, {len(cases)} tests, {len(failed)} failed (compile error or wrong test filter?)")
    code, cases, failed, log = green
    green_ok = code == 0 and bool(cases)  # the exit code decides: a retried attempt may fail first
    green_ok or print(*log.splitlines()[-40:], sep="\n")
    green = f"{len(cases)} of {len(cases)} passed" if green_ok else \
        f"not Green: exit {code}, {len(cases)} tests, {len(failed)} failed"
    print(f"\n{cve_id}: {'ok' if red_ok and green_ok else 'FAILED'}\n"
          f'  red: {{result: "{red}", date: {date.today()}}}\n'
          f'  green: {{result: "{green}", date: {date.today()}}}\n')
    return red_ok and green_ok


def main(args):
    if not args:
        return check()
    command, targets = args[0], args[1:]
    if args == ["index"]:
        INDEX.write_text(index())
        return True
    if command == "apply":
        with ThreadPoolExecutor() as pool:
            return all(pool.map(apply, targets or PROJECTS))
    if command == "cve":
        ids = targets or [i for i, c in CVES.items() if (c.get("verify") or {}).get("tests")]
        if unknown := [i for i in ids if i not in CVES]:
            raise SystemExit(f"error: no such CVE: {unknown}")
        return prove(ids)
    print(__doc__.strip(), file=sys.stderr)
    return False


if __name__ == "__main__":
    sys.exit(0 if main(sys.argv[1:]) else 1)
